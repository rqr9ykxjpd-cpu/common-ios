def parse(entry):
    if len(entry) == 3:
        key, tr, en = entry
        args = []
    else:
        key, tr, en, args = entry
    return key, tr, en, args


def swift_ident(name: str) -> str:
    parts = name.split(".")
    ident = parts[0]
    for p in parts[1:]:
        ident += p[:1].upper() + p[1:]
    if ident and ident[0].isdigit():
        ident = "n" + ident
    if ident in {"repeat", "continue", "return", "class", "default", "switch"}:
        ident += "_"
    return ident


def swift_literal(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def emit_property(key: str, args: list) -> str:
    ident = swift_ident(key.split(".", 1)[1])
    loc = swift_literal(key)
    if not args:
        return f"        static var {ident}: String {{ String(localized: {loc}) }}"
    params = []
    call_args = []
    for name, typ in args:
        params.append(f"_ {name}: {typ}")
        if typ == "Int":
            call_args.append(f"Int64({name})")
        else:
            call_args.append(name)
    joined = ", ".join(call_args)
    return (
        f"        static func {ident}({', '.join(params)}) -> String {{\n"
        f"            L10n.format({loc}, {joined})\n"
        f"        }}"
    )


def write_xcstrings(path: Path, items: dict[str, tuple[str, str]]):
    strings = {}
    for key, (tr, en) in items.items():
        strings[key] = {
            "extractionState": "manual",
            "localizations": {
                "en": {"stringUnit": {"state": "translated", "value": en}},
                "tr": {"stringUnit": {"state": "translated", "value": tr}},
            },
        }
    payload = {"sourceLanguage": "tr", "strings": strings, "version": "1.0"}
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def write_l10n_files():
    by_prefix: dict[str, list] = defaultdict(list)
    for entry in S:
        key, tr, en, args = parse(entry)
        prefix = key.split(".", 1)[0]
        by_prefix[prefix].append((key, args))

    for prefix, rows in by_prefix.items():
        enum = PREFIX_ENUM[prefix]
        lines = [
            "import Foundation",
            "",
            f"extension L10n {{",
            f"    enum {enum} {{",
        ]
        for key, args in rows:
            lines.append(emit_property(key, args))
        lines += ["    }", "}"]
        (L10N_DIR / f"L10n+{enum}.swift").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    catalog = {}
    seen = set()
    for entry in S:
        key, tr, en, _ = parse(entry)
        if key in seen:
            raise SystemExit(f"duplicate key: {key}")
        seen.add(key)
        catalog[key] = (tr, en)
    write_xcstrings(STRINGS_PATH, catalog)
    write_xcstrings(INFOPLIST_PATH, INFO_PLIST)
    L10N_DIR.mkdir(parents=True, exist_ok=True)
    write_l10n_files()
    print(f"  {len(catalog)} keys -> {STRINGS_PATH.relative_to(ROOT)}")
    print(f"  {len(INFO_PLIST)} keys -> {INFOPLIST_PATH.relative_to(ROOT)}")
    print(f"  {len(PREFIX_ENUM)} L10n files in {L10N_DIR.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
